import {createResidentActivityCache,RESIDENT_ACTIVITY_KEY,RESIDENT_ACTIVITY_TTL,residentActivityStamp,captureResidentActivity,restoreResidentActivity,seedResidentActivity} from '../src/core/resident-activity.js';
let checks=0;
const check=(v,label)=>{if(!v)throw Error(label);checks++};
const memory=new Map();let writes=0;
const store={getItem:k=>memory.get(k),setItem(k,v){writes++;memory.set(k,v)},removeItem:k=>memory.delete(k)};
const cache=createResidentActivityCache(()=>store),now=1700000000000;
const actor=()=>({x:0,y:0,z:0,yaw:0,wait:0,path:null,pi:0,hidden:false,entry:[8,'plaza','wander']});
const spot=[0,0],stamp=residentActivityStamp(actor().entry,spot);
const pointAt=(x,z,y=0)=>Number.isFinite(x)&&Number.isFinite(z)&&Math.abs(x)<20&&Math.abs(z)<20?{x,y:0,z}:null;
const opts={stamp,spot,pointAt,queue(n,x,z){n.queued=[x,z]}};
const n=actor();n.x=3;n.path=[[2,0],[8,0]];n.pi=1;n.yaw=1;
const record=captureResidentActivity(n,stamp);
check(record.x===3&&record.target[0]===8&&!('path'in record),'compact progress');
check(cache.write('kael',1,{a:record},now),'write');
check(cache.read(now+RESIDENT_ACTIVITY_TTL)?.entries.a.x===3,'inclusive 30 minutes');
check(cache.read(now+RESIDENT_ACTIVITY_TTL+1)===null,'expired');
check(cache.read(now-1)===null,'future timestamp');
const restored=actor();
check(restoreResidentActivity(restored,cache.read(now).entries.a,opts),'restore');
check(restored.x===3&&restored.yaw===1&&restored.queued[0]===8&&restored.path===null,'resume position and replan target');
check(!restoreResidentActivity(actor(),record,{...opts,stamp:'changed'}),'changed schedule or place');
check(!restoreResidentActivity(actor(),{...record,x:99},opts),'invalid terrain');
check(!restoreResidentActivity(actor(),{...record,target:[99,0]},opts),'invalid destination');
check(!restoreResidentActivity(actor(),{...record,hidden:true},opts),'invalid hidden');
check(!restoreResidentActivity(actor(),{...record,wait:-1},opts),'invalid wait');
check(captureResidentActivity(n,stamp,[4,5]).target[1]===5,'pending target wins');
const idle=actor();idle.wait=8;
check(restoreResidentActivity(idle,captureResidentActivity(idle,stamp),opts)&&idle.wait===8&&!idle.queued,'idle wait');
const h={...actor(),entry:[0,'home'],hidden:true},hs=residentActivityStamp(h.entry,spot);
check(restoreResidentActivity(h,captureResidentActivity(h,hs),{...opts,stamp:hs}),'home remains hidden');
check(!restoreResidentActivity(actor(),{...record,target:null,x:0,y:9},opts),'invalid height');
check(cache.write('kael',1,{a:record},now+15000)&&writes===1,'unchanged checkpoint skipped');
check(cache.write('kael',1,{a:record},now+60000)&&writes===2,'heartbeat');
check(cache.write('kael',1,{a:{...record,x:4}},now+75000)&&writes===3,'dirty checkpoint');
check(cache.write('kael',1,{a:{...record,x:4}},now+76000,true)&&writes===4,'hide flush');
check(cache.write('kael',1,{a:{...record,x:4}},now+76001,true)&&writes===4,'duplicate hide flush');
memory.set(RESIDENT_ACTIVITY_KEY,'{');check(cache.read(now)===null,'corrupt data');
memory.set(RESIDENT_ACTIVITY_KEY,JSON.stringify({version:2,savedAt:now,regionId:'kael',day:1,entries:{}}));check(cache.read(now)===null,'future version');
check(!createResidentActivityCache(()=>{throw Error('quota')}).write('kael',1,{},now),'storage failure');
check(createResidentActivityCache(()=>{throw Error('disabled')}).read(now)===null,'disabled storage');
cache.clear();check(!memory.has(RESIDENT_ACTIVITY_KEY),'reset');
const values=[.3,.1,.2,.4,.7];const walker=actor();
check(seedResidentActivity(walker,{random:()=>values.shift(),pointAt,segment:()=>true}),'cold moving phase');
check(Math.hypot(walker.x,walker.z)>0&&walker.path?.length===1,'intermediate position');
const waiter=actor();check(!seedResidentActivity(waiter,{random:()=>.8,pointAt,segment:()=>true})&&waiter.wait>0&&!waiter.path,'cold idle phase');
const worker={...actor(),entry:[8,'stall','work']};
check(!seedResidentActivity(worker,{random:()=>0,pointAt,segment:()=>true})&&!worker.path,'work remains work');
const blocked=actor();check(!seedResidentActivity(blocked,{random:()=>.1,pointAt,segment:()=>false})&&blocked.wait>0&&!blocked.path,'blocked initial route');
console.log('PASS resident activity cache: '+checks+' checks');
