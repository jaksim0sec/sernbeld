import {createLivingWorldRegistry} from '../src/core/living-world-registry.js';
import {createLivingWorldState} from '../src/core/living-world-state.js';
import {createItemRuntime,extendItemDefinitions} from '../src/core/shared-items.js';
const a=(x,m)=>{if(!x)throw Error(m)};
const registry=createLivingWorldRegistry({handlers:['rest'],regions:['kael'],places:['home']});
const defs=extendItemDefinitions({flower:{kind:'material',rarity:'common',name:'flower',value:2}});
const data={needs:[{id:'hunger',min:0,max:100,initial:80,perTick:1,threshold:60}],actions:[{id:'rest',handlerId:'rest',duration:2,interruptPolicy:'pauseable',needWeights:{hunger:1}}],roles:[{id:'worker',actionIds:['rest'],needWeights:{hunger:1}}],profiles:[{id:'a',roleId:'worker',regionId:'kael',tags:['worker']}]};
a(registry.validateRegistry().ok,'empty registry valid');
a(!registry.registerDefinitions({...data,actions:[{...data.actions[0],handlerId:'missing'}]}).ok&&registry.list('needs').length===0,'atomic registration failure');
a(!registry.registerDefinitions({...data,profiles:[{...data.profiles[0],roleId:'missing'}]}).ok,'unknown role');
a(registry.registerDefinitions(data).ok,'valid registration');
a(!registry.registerDefinitions(data).ok,'duplicate registration');
a(Object.isFrozen(registry.get('needs','hunger')),'definitions immutable');
let writes=0;
const save={data:{v:1,money:20,inv:{flower:3},npcStates:{a:{region:'kael',lineI:4,relationships:{player:{talks:3}},resources:{old:1},memory:{met:true},activity:'selling'}}},write(){writes++;return true}};
const s=createLivingWorldState(save,registry,()=>defs);
a(s.initialize({worldTick:10,seed:9}).ok,'migration');
const snap=JSON.stringify(save.data);
a(save.data.npcStates.a.lineI===4&&save.data.npcStates.a.relationships.player.talks===3&&save.data.npcStates.a.resources.old===1&&save.data.npcStates.a.memory.met===true,'legacy state preserved');
const items=createItemRuntime(save,()=>defs);
a(items.balance()===20&&items.count('flower')===3&&items.balance('npc:a')===0,'single economy and empty actor');
const axes=s.projectState('a');
a(axes.body.tags.includes('hunger')&&axes.economy.tags.includes('no_stock')&&axes.business.state==='selling','independent state axes');
a(s.initialize().changed===false&&writes===1&&JSON.stringify(save.data)===snap,'idempotent initialization');
const future={data:{...JSON.parse(snap),livingWorld:{...s.snapshot(),version:2}},write(){throw Error('must not write')}};
const original=JSON.stringify(future.data);
a(createLivingWorldState(future,registry,()=>defs).initialize().reason==='unsupported_version'&&JSON.stringify(future.data)===original,'future save preserved');
const broken={data:{...JSON.parse(snap),npcStates:{a:{needs:{hunger:101}}}},write(){throw Error('must not write')}};
const b=JSON.stringify(broken.data);
a(createLivingWorldState(broken,registry,()=>defs).initialize().reason==='invalid_needs'&&JSON.stringify(broken.data)===b,'corrupt needs preserved');
const failed={data:{v:1,inv:{flower:2}},write(){this.data.extra=true;return false}};
const before=JSON.stringify(failed.data);
a(createLivingWorldState(failed,registry,()=>defs).initialize().reason==='save_failed'&&JSON.stringify(failed.data)===before,'migration rollback');
const empty=createLivingWorldRegistry();
a(createLivingWorldState({data:{v:1},write(){return true}},empty,()=>defs).initialize().ok,'empty data startup');
console.log('PASS living world registry/state: 15 checks');
