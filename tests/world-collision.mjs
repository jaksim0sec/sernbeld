import {createWorldCollision,legacyCollisionPolicy,classifySupport,slopeGravity} from '../src/core/world-collision.js';

function runTests(createWorldCollision,legacyCollisionPolicy,classifySupport,slopeGravity){
 let count=0;const check=(v,msg)=>{if(!v)throw Error(msg);count++},throws=(fn,msg)=>{let ok=false;try{fn()}catch{ok=true}check(ok,msg)},near=(a,b)=>Math.abs(a-b)<1e-9;
 const world=createWorldCollision(),p=legacyCollisionPolicy({walk:false});
 check(p.support&&p.block&&!p.nav&&p.climb==="face","legacy box policy");
 check(legacyCollisionPolicy({shape:"cylinder"}).climb==="none","cylinder opt in");
 check(legacyCollisionPolicy({shape:"cylinder",climbable:true,mantleOnly:true}).climb==="mantleOnly","rounded rock");
 const raw={id:"lab:box",regionId:"lab",physics:"solid",transform:{position:[4,0,0],yaw:Math.PI/2,scale:[2,1,1]},shapes:[{id:"main",type:"box",center:[0,1,0],half:[1,1,.5],policy:p}]};
 const h=world.register(raw),q={min:[3.4,0,-2.1],max:[4.6,2,2.1]},f={regionId:"lab",purpose:"support"};
 const s=world.get(raw.id),b=s.shapes[0].worldBounds;
 check(near(b.min[0],3.5)&&near(b.max[2],2)&&near(b.max[1],2),"rotated box bounds");
 check(world.queryAabb(q,f).length===1,"support filter");
 check(world.queryAabb(q,{...f,purpose:"nav"}).length===0,"nav filter independent");
 check(world.queryAabb(q,{...f,actorId:raw.id}).length===0,"self excluded");
 check(world.queryAabb(q,{...f,layerMask:2}).length===0,"layer mask");
 throws(()=>world.register(raw),"duplicate instance");
 throws(()=>world.register({...raw,id:"bad",transform:{...raw.transform,pitch:1}}),"unsupported transform");
 throws(()=>world.register({...raw,id:"bad",shapes:[...raw.shapes,...raw.shapes]}),"duplicate shape");
 throws(()=>world.register({...raw,id:"bad",shapes:[{...raw.shapes[0],half:[1,-1,1]}]}),"negative extent");
 check(world.get("bad")===null,"atomic validation");
 raw.shapes[0].half[0]=999;check(world.get(raw.id).shapes[0].half[0]===1,"source mutation isolated");
 s.shapes[0].half[0]=999;check(world.get(raw.id).shapes[0].half[0]===1,"snapshot isolated");
 const rev=world.get(raw.id).revision;check(world.resolveShape(raw.id,"main",rev,f)!==null,"resolve stable revision");
 world.suspendRegion("lab");check(world.queryAabb(q,f).length===0,"suspend");
 world.resumeRegion("lab");check(world.queryAabb(q,f).length===1&&world.resolveShape(raw.id,"main",rev,f)===null,"resume invalidates anchor");
 world.setActive(h,false);world.suspendRegion("lab");world.resumeRegion("lab");check(world.queryAabb(q,f).length===0,"individual inactive preserved");
 world.setActive(h,true);world.updateTransform(h,{position:[20,0,0],yaw:0,scale:[1,1,1]});check(world.queryAabb(q,f).length===0,"move bounds");
 world.remove(h);check(world.get(raw.id)===null,"remove");
 raw.shapes[0].half[0]=1;const h2=world.register(raw);throws(()=>world.remove(h),"stale handle cannot remove replacement");
 check(world.get(raw.id)!==null,"replacement intact");
 world.register({...raw,id:"lab:decor",physics:"decorative",shapes:[]});
 check(world.queryAabb(q,f).length===1,"decorative omitted");
 const wet={id:"water",block:false,support:false,mantle:false,oneWay:false,nav:false,camera:false,water:true,climb:"none"};
 world.register({...raw,id:"lab:pool",physics:"volume",shapes:[{id:"volume",type:"water",center:[0,1,0],half:[1,1,1],policy:wet}]});
 check(world.queryAabb(q,{...f,purpose:"water"}).length===1&&world.queryAabb(q,f).length===1,"water is not ground");
 throws(()=>world.register({...raw,id:"bad",physics:"volume",shapes:raw.shapes}),"bad volume");
 throws(()=>world.register({...raw,id:"bad",shapes:[{id:"c",type:"cylinder",center:[0,0,0],radius:1,height:2,policy:p}]}),"unequal radial scale");
 const cyl=world.register({...raw,id:"lab:cyl",transform:{position:[0,0,0],yaw:1,scale:[2,1,2]},shapes:[{id:"c",type:"cylinder",center:[0,1,0],radius:1,height:2,policy:p}]});
 check(near(world.get(cyl.id).shapes[0].worldBounds.min[0],-2),"cylinder bounds");
 throws(()=>world.raycast({},f),"missing backend fails explicitly");
 check(!world.capabilities().sweepBody,"no false capability");
 let consulted=false;
 const delegated=createWorldCollision({backend:{sampleSupport:(args,filter,resolve)=>{consulted=true;return resolve(args.id,"main",args.revision);}}});
 delegated.register({...raw,id:"x"});
 check(delegated.sampleSupport({id:"x",revision:delegated.get("x").revision},f)?.shapeId==="main"&&consulted,"backend gets resolver");
 check(delegated.sampleSupport({id:"x",revision:delegated.get("x").revision},{...f,purpose:"nav"})===null,"backend policy resolution");
 const rad=d=>d*Math.PI/180,n=d=>[Math.sin(rad(d)),Math.cos(rad(d)),0],cl=d=>classifySupport({geometricNormal:n(d),support:true,footContact:true,walkMax:rad(50)});
 for(const d of [0,30,45,49.9,50])check(cl(d).kind==="walk","walk "+d);
 for(const d of [50.1,60,80,89])check(cl(d).kind==="slide","slide "+d);
 check(cl(90).kind==="unsupported"&&cl(100).kind==="unsupported","walls and ceiling not support");
 check(classifySupport({geometricNormal:n(60),support:true,footContact:false,walkMax:rad(50)}).kind==="unsupported","support needs foot contact");
 check(classifySupport({geometricNormal:n(50),support:true,footContact:true,walkMax:rad(50),slideEnter:rad(50.5),slideExit:rad(49.5),previous:"slide"}).kind==="slide","hysteresis retains slide");
 const g=slopeGravity(n(60),24);check(near(g[0],24*Math.sin(rad(60))*Math.cos(rad(60)))&&near(g[0]*n(60)[0]+g[1]*n(60)[1],0),"gravity tangent");
 check(slopeGravity(n(0),24).every(v=>v===0),"flat gravity tangent zero");
 throws(()=>cl(180+NaN),"nonfinite normal");return count;
}
console.log('PASS: '+runTests(createWorldCollision,legacyCollisionPolicy,classifySupport,slopeGravity)+' world collision assertions');
