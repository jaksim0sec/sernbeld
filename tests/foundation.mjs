#!/usr/bin/env node
import assert from 'node:assert/strict';
import {createGameEvents} from '../src/core/game-events.js';
import {createEntityRegistry} from '../src/core/entity-registry.js';
import {createInventory} from '../src/core/inventory.js';

const failures=[];
const events=createGameEvents({onError:(error)=>failures.push(error.message)});
const seen=[];
const off=events.on('inventory.changed',ev=>seen.push(ev));
events.on('inventory.changed',()=>{throw Error('listener failed');});
events.emit('inventory.changed',{itemId:'stone',quantity:2});
assert.equal(seen.length,1);
assert.equal(failures[0],'listener failed');
off();events.emit('inventory.changed',{itemId:'stone',quantity:1});
assert.equal(seen.length,1,'unsubscribe stops notifications');
assert.throws(()=>events.on('',()=>{}),/type/);

const entities=createEntityRegistry();
const person={name:'sample'}, beast={name:'beast'};
entities.register({id:'resident:0',kind:'resident',region:'kael',ref:person});
entities.register({id:'wildlife:0',kind:'wildlife',region:'kael',ref:beast});
entities.register({id:'resident:1',kind:'resident',region:'woods',ref:{}});
assert.equal(entities.get('resident:0')?.ref,person);
assert.equal(entities.list({region:'kael'}).length,2);
assert.equal(entities.list({kind:'resident'}).length,2);
assert.throws(()=>entities.register({id:'resident:0',kind:'resident',region:'kael',ref:{}}),/Duplicate/);
assert.equal(entities.removeRegion('kael'),2);
assert.equal(entities.get('resident:0'),null);
assert.equal(entities.list().length,1);

const legacy={v:1,inv:{flower:3},money:4};
const save={data:legacy};
const inventoryEvents=[];
const invEvents=createGameEvents();invEvents.on('inventory.changed',e=>inventoryEvents.push(e));
const bag=createInventory(save,invEvents);
assert.equal(bag.count('flower'),3,'legacy stack is readable');
assert.equal(bag.add('flower',2),5);
assert.equal(bag.take('flower',4),true);
assert.equal(bag.count('flower'),1);
assert.equal(bag.take('flower',2),false,'insufficient stock does not mutate');
assert.deepEqual(bag.entries(),[['flower',1]]);
assert.throws(()=>bag.add('flower',0),/quantity/);
assert.throws(()=>bag.take('flower',1.5),/quantity/);
const blade=bag.makeUnique('apprentice_sword',{name:'첫 검',craftedBy:'player'});
assert.equal(blade.itemId,'apprentice_sword');
assert.equal(bag.getUnique(blade.id)?.state.name,'첫 검');
assert.equal(bag.count('apprentice_sword'),0,'simple stacks exclude unique items');
assert.equal(bag.uniqueEntries().length,1);
const blade2=bag.promote('flower',{note:'첫 탐험 기념'});
assert.equal(bag.count('flower'),0,'promoted item no longer in simple stack');
assert.equal(save.data.inv.flower,undefined,'promote consumes quantity from simple stack');
assert.equal(bag.getUnique(blade2.id)?.state.note,'첫 탐험 기념');
assert.equal(bag.removeUnique(blade.id),true);
assert.equal(bag.count('apprentice_sword'),0);
assert.equal(inventoryEvents.length,5,'successful changes notify; failed changes do not');
const snapshot=JSON.parse(JSON.stringify(save.data));
const restored=createInventory({data:snapshot},createGameEvents());
assert.equal(restored.getUnique(blade2.id)?.state.note,'첫 탐험 기념','unique state persists');
assert.equal(restored.makeUnique('flower').id!==blade2.id,true,'serial never reuses existing id');
console.log('PASS: foundation events, registry and inventory');

await import('./world-performance.mjs');
