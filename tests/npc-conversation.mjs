import {createLivingWorldRegistry} from '../src/core/living-world-registry.js';
import {createNpcConversations} from '../src/core/npc-conversation.js';
let checks=0;const a=(v,m)=>{if(!v)throw Error(m);checks++};
const r=createLivingWorldRegistry({regions:['kael'],societyHandlers:['e','p']});
const t={id:'talk',topic:'supply',regionIds:['kael'],slots:[{id:'speaker',tags:['worker']},{id:'listener',tags:['worker']}],eventTypeId:'shortage',factRefs:[{key:'amount',slotId:'speaker',factKey:'amount'}],turns:[{slotId:'speaker',text:'fixture {amount}',duration:12},{slotId:'listener',text:'fixture reply',duration:15}]};
const e={id:'shortage',regionIds:['kael'],evaluateHandlerId:'e',propagationHandlerId:'p',minIntensity:0,maxIntensity:10,factKeys:['amount']};
a(!r.registerDefinitions({eventTypes:[e],conversationTemplates:[{...t,turns:[{slotId:'listener',text:'{amount}',duration:1}]}]}).ok,'speaker cannot use unknown fact');
a(r.registerDefinitions({eventTypes:[e],conversationTemplates:[t]}).ok,'register');
const person=(id,x,tags=['worker'])=>({id,x,y:0,z:0,tags,stationary:true});
let ns=[person('a',0),person('b',2),person('c',4),person('d',.5,['other'])],rev=1,held=new Set(),releases=0;
const m=createNpcConversations({registry:r,knownEvents:id=>id==='a'?[{id:'event:1',typeId:'shortage',revision:rev,state:'active',facts:{amount:3}}]:[],canPair:()=>true,hold:id=>{if(held.has(id))return false;held.add(id);return true},release:id=>{held.delete(id);releases++}});
const update=(now,x,active=true)=>m.update({active,regionId:'kael',player:{x,y:0,z:0},npcs:ns,now});
a(update(0,100,false).length===0&&m.snapshot().stats.scans===0,'L0 zero');
a(update(1,100).length===0&&m.snapshot().stats.scans===0,'L1 zero');
let lines=update(2,-12);a(lines.length===1&&lines[0].text==='···'&&lines[0].lod===2,'L2 dots');
a(m.snapshot().stats.materializations===0&&held.size===2,'L2 lazy and no chain');
const gid=lines[0].groupId;
lines=update(3,0);a(lines[0].templateId==='talk'&&lines[0].text==='fixture 3','L3 fact materialization');
a(m.snapshot().stats.materializations===1,'one materialization');
a(update(4,-8)[0].lod===3,'hysteresis');
a(update(5,-10)[0].text==='···','L2 exit');
lines=update(15,0);a(lines[0].groupId===gid&&lines[0].cursor===1&&lines[0].text==='fixture reply','cursor continuity');
a(m.snapshot().stats.materializations===1,'no reroll');
rev=2;a(update(16,0).length===0&&held.size===0&&releases===2,'stale revision releases group');
a(update(17,0).length===0,'cooldown');
const no=createNpcConversations({registry:r,canPair:()=>false});
a(no.update({active:true,regionId:'kael',player:{x:0,y:0,z:0},npcs:ns,now:0}).length===0,'blocked pair');
const dense=createNpcConversations({registry:r,canPair:()=>true,config:{maxPairs:12,maxCandidates:16}});
const many=Array.from({length:100},(_,i)=>person('n'+i,i%4*.2));
const q=dense.update({active:true,regionId:'kael',player:{x:0,y:0,z:0},npcs:many,now:0});
a(q.every(g=>g.npcIds.length<=4)&&new Set(q.flatMap(g=>g.npcIds)).size===q.flatMap(g=>g.npcIds).length,'bounded exclusive groups');
a(dense.snapshot().stats.pairs<=12,'pair budget');
dense.clear(1);a(dense.snapshot().groups.length===0,'region release');
console.log('PASS NPC conversation groups: '+checks+' checks');
