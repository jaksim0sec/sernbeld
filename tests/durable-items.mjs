import assert from 'node:assert/strict';
import { createInventory } from '../src/core/inventory.js';
let writes=0; const messages=[];
const save={data:{v:1,inv:{sword:2,flower:1}},write(){writes++}};
const inventory=createInventory(save,{emit(type,record){messages.push({type,...record})}});
const a=inventory.promote('sword',{name:'기념 검',history:{owner:'player'}});
assert.equal(writes,1,'promote must commit to persistent save immediately');
assert.equal(inventory.count('sword'),1);
a.state.name='changed outside store';
assert.equal(inventory.getUnique(a.id).state.name,'기념 검','return copies, not live references');
const v=inventory.getUnique(a.id);v.state.history.owner='hacker';
assert.equal(inventory.getUnique(a.id).state.history.owner,'player','nested objects must be copies');
const b=inventory.updateUnique(a.id,{history:{owner:'player',upgrade:1}});
assert.equal(b.state.history.upgrade,1);
assert.equal(writes,2,'explicit update persists immediately');
assert.deepEqual(messages.map(x=>x.action),['promoted','unique-updated']);
assert.equal(inventory.updateUnique('missing',{x:1}),null,'missing ID must not mutate');
assert.equal(writes,2);
assert.throws(()=>inventory.updateUnique(a.id,undefined),/state/i);
assert.throws(()=>inventory.updateUnique(a.id,[]),/state/i);
assert.equal(inventory.makeUnique('flower',{note:'hello'}).itemId,'flower');
assert.equal(writes,3,'new unique persists');
assert.equal(inventory.removeUnique(a.id),true);
assert.equal(writes,4,'removing unique persists');
const persisted=JSON.parse(JSON.stringify(save.data));
const restored=createInventory({data:persisted});
assert.equal(restored.uniqueEntries().length,1);
assert.deepEqual(restored.uniqueEntries()[0].state,{note:'hello'});
assert.equal(inventory.removeUnique(a.id),false);
assert.equal(writes,4,'no change does not write');
console.log('PASS detailed items: durable mutations, defensive snapshots, save restoration');
